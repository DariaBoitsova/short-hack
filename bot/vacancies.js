export function getWeights(vacancyId) {
  const r = WEIGHTS_RAW[vacancyId] || [0.35, 0.35, 0.3];
  const [h, s, m] = r;
  const sum = h + s + m;
  return { hard: h / sum, soft: s / sum, motiv: m / sum };
}

